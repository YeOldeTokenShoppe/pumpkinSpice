export default function ScrollDisplay({ scrollPath = '/scroll.html', style = {} }) {
  const containerRef = useRef(null);
  const contentRef = useRef(null);
  const [panels, setPanels] = useState({ tops: [], bottoms: [] });
  const scrollContentRef = useRef(null);
  
  // Get the appropriate content based on scrollPath
  const scrollData = scrollContents[scrollPath] || scrollContents['/scroll.html'];
  
  useEffect(() => {
    // Load the UnifrakturMaguntia font if not already loaded
    const link = document.querySelector('link[href*="UnifrakturMaguntia"]');
    if (!link) {
      const fontLink = document.createElement('link');
      fontLink.rel = 'stylesheet';
      fontLink.href = 'https://fonts.googleapis.com/css?family=UnifrakturMaguntia';
      document.head.appendChild(fontLink);
    }
  }, []);

  // Create the rolled paper effect
  useEffect(() => {
    if (!contentRef.current) return;

    const isMobile = /iPhone|Android/.test(navigator.userAgent);
    const theta = isMobile ? 0.45 : 0.3;
    const num = isMobile ? 10 : 20;
    const panelHeight = 20;

    // Sync panel content based on scroll
    const syncPanelContent = (scrollTop) => {
      const containerHeight = containerRef.current?.clientHeight || 400;
      panels.tops.forEach((panel, i) => {
        const tTop = (i + 1) * panelHeight - scrollTop;
        const bTop = -i * panelHeight - scrollTop - containerHeight;
        if (panel.current) {
          panel.current.style.transform = `translate3d(0,${tTop}px,0)`;
        }
        if (panels.bottoms[i]?.current) {
          panels.bottoms[i].current.style.transform = `translate3d(0,${bTop}px,0)`;
        }
      });
    };

    const handleScroll = () => {
      if (scrollContentRef.current) {
        requestAnimationFrame(() => {
          syncPanelContent(scrollContentRef.current.scrollTop);
        });
      }
    };

    if (scrollContentRef.current) {
      scrollContentRef.current.addEventListener('scroll', handleScroll);
      // Set initial scroll position
      scrollContentRef.current.scrollTop = 110;
    }

    return () => {
      if (scrollContentRef.current) {
        scrollContentRef.current.removeEventListener('scroll', handleScroll);
      }
    };
  }, [panels]);

  return (
    <div 
      ref={containerRef}
      className="scroll-container"
      style={{
        fontFamily: 'UnifrakturMaguntia, serif',
        width: '22rem',
        height: '60%',
        maxHeight: '45rem',
        top: '50%',
        left: '50%',
        perspective: '290rem',
        transform: 'translate(-50%, -50%) rotateY(20deg)',
        fontSize: '1em',
        position: 'absolute',
        transformStyle: 'preserve-3d',
        ...style
      }}
    >
      <div 
        ref={contentRef}
        className="scroll-panel-wrapper"
        style={{
          width: '100%',
          height: '100%',
          position: 'relative',
          transformStyle: 'preserve-3d'
        }}
      >
        {/* Main scrollable content */}
        <div 
          ref={scrollContentRef}
          className="scroll-content"
          style={{
            width: '100%',
            height: '100%',
            overflowY: 'scroll',
            overflowX: 'hidden',
            background: '#fefee0',
            color: '#000',
            msOverflowStyle: 'none',
            scrollbarWidth: 'none',
            position: 'relative',
            zIndex: 10
          }}
        >
          <div style={{ padding: '0 0.3rem 0 1rem' }}>
            {scrollData.content}
          </div>
        </div>

        {/* Top curl panels */}
        <div className="panels-top" style={{
          position: 'absolute',
          top: 0,
          left: 0,
          width: '100%',
          transformStyle: 'preserve-3d',
          pointerEvents: 'none'
        }}>
          {[...Array(10)].map((_, i) => (
            <div key={`top-${i}`} style={{
              position: 'absolute',
              width: '100%',
              height: '20px',
              transformOrigin: '50% 100% 0',
              transform: `translate3d(0, ${-20 + (i === 0 ? 0 : 0.25)}px, 0) rotateX(${i === 0 ? 0 : 0.3 + i * 0.025}rad)`,
              transformStyle: 'preserve-3d'
            }}>
              <div style={{
                width: '100%',
                height: '100%',
                overflow: 'hidden',
                background: '#fefee0',
                opacity: i > 5 ? 0.25 : 1
              }}>
                <div className="panel-content" style={{
                  transform: `translate3d(0, ${(i + 1) * 20}px, 0)`,
                  padding: '0 0.3rem 0 1rem'
                }}>
                  {scrollData.content}
                </div>
              </div>
            </div>
          ))}
        </div>

        {/* Bottom curl panels */}
        <div className="panels-bottom" style={{
          position: 'absolute',
          top: '100%',
          left: 0,
          width: '100%',
          transformStyle: 'preserve-3d',
          pointerEvents: 'none'
        }}>
          {[...Array(10)].map((_, i) => (
            <div key={`bottom-${i}`} style={{
              position: 'absolute',
              width: '100%',
              height: '20px',
              transformOrigin: '50% 0% 0',
              transform: `translate3d(0, ${i === 0 ? 0 : 20 - 0.25}px, 0) rotateX(${i === 0 ? 0 : 0.3 + i * 0.025}rad)`,
              transformStyle: 'preserve-3d'
            }}>
              <div style={{
                width: '100%',
                height: '100%',
                overflow: 'hidden',
                background: '#fefee0',
                opacity: i > 5 ? 0.25 : 1
              }}>
                <div className="panel-content" style={{
                  transform: `translate3d(0, ${-i * 20 - 400}px, 0)`,
                  padding: '0 0.3rem 0 1rem'
                }}>
                  {scrollData.content}
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>
      
      <style jsx>{`
        .scroll-content::-webkit-scrollbar {
          display: none;
        }
        
        .scroll-lorem {
          font-size: 7em;
          float: left;
          color: red;
          border: 1px solid black;
          margin-right: 5px;
          line-height: 0.8;
        }
        
        .scroll-content hr {
          margin: 0 1rem;
          border: none;
          border-top: 1px solid #8b7355;
        }
        
        .scroll-content p {
          padding: 0 0.3rem 0 1rem;
          margin-bottom: 1rem;
          text-align: justify;
        }
        
        .scroll-content u {
          text-decoration: underline;
          font-weight: bold;
        }
        
        @media (min-width: 1025px) {
          .scroll-container {
            width: 28rem !important;
            height: 60% !important;
            max-height: 50rem !important;
            font-size: 1.1em !important;
          }
        }
        
        @media (min-width: 769px) and (max-width: 1024px) and (max-height: 768px) {
          .scroll-container {
            width: 16rem !important;
            height: 60vh !important;
            max-height: 35rem !important;
            font-size: 0.9em !important;
          }
        }
        
        @media (max-width: 768px) {
          .scroll-container {
            height: 60vh !important;
            max-height: none !important;
            font-size: 1em !important;
          }
          
          .scroll-lorem {
            font-size: 5em;
          }
        }
      `}</style>
    </div>
  );
}